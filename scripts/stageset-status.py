#!/usr/bin/env python3
"""StageSet status, digest, sync, validation, and escalation tool."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
META = re.compile(r"@stageset\s+([a-z_]+):\s*(.*?)\s*$")
EVENT_TYPES = {"IDEATION", "PROBE", "CODING", "PUSH", "MAINTENANCE"}
SKELETON_STATES = {"DRAFT", "READY", "IN_PROGRESS", "DONE", "BLOCKED", "SUPERSEDED"}
IDEA_STATES = {"DISCOVERY", "CLARIFIED", "DECIDED", "READY_FOR_SKELETON", "SKELETONIZED", "IMPLEMENTED", "PARKED", "REJECTED"}
RUN_RESULTS = {"PASS", "FAIL", "BLOCKED"}
GENERATED = "<!-- GENERATED BY scripts/stageset-status.py. DO NOT EDIT. -->"


def scalar(value: str) -> str:
    value = value.split(" #", 1)[0].strip()
    if len(value) > 1 and value[0] == value[-1] and value[0] in "'\"":
        return value[1:-1]
    return value


def parse_config(path: Path) -> dict[str, str]:
    if not path.is_file():
        raise ValueError(f"Missing config: {path}")
    values: dict[str, str] = {}
    section = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^(\s*)([A-Za-z0-9_-]+):\s*(.*)$", line)
        if not match or not line.strip() or line.lstrip().startswith("#"):
            continue
        indent, key, value = match.groups()
        value = scalar(value)
        if not indent:
            section = key if not value else ""
        elif len(indent.replace("\t", "  ")) == 2:
            values[f"{section}.{key}"] = value
    return values


def inside(base: Path, value: str, label: str) -> Path:
    path = (base / value).resolve()
    try:
        path.relative_to(ROOT.resolve())
    except ValueError as exc:
        raise ValueError(f"{label} must stay inside the repository: {value}") from exc
    return path


def front_matter(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end < 0:
        return {}, text
    data: dict[str, str] = {}
    for line in text[4:end].splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        data[key.strip()] = scalar(value)
    return data, text[end + 4:]


def git_time(path: Path, timezone: ZoneInfo) -> str | None:
    try:
        raw = subprocess.check_output(
            ["git", "log", "-1", "--format=%cI", "--", str(path.relative_to(ROOT))],
            cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
        if not raw:
            return None
        dt = datetime.fromisoformat(raw).astimezone(timezone)
        return dt.isoformat(timespec="seconds")
    except (OSError, subprocess.CalledProcessError, ValueError):
        return None


def files_in(folder: Path, suffix: str = ".md") -> list[Path]:
    return sorted(p for p in folder.rglob(f"*{suffix}") if p.is_file()) if folder.is_dir() else []


def timestamp_id(kind: str, folder: Path, timezone: str) -> tuple[str, str]:
    """Return a timestamp ID and its local timestamp. Add a suffix on collision."""
    now = datetime.now(ZoneInfo(timezone))
    base = now.strftime("%Y%m%d-%H%M%S") + "-" + kind
    candidate = base
    suffix = 2
    while (folder / f"{candidate}.md").exists() or (folder / f".{candidate}.reserve").exists():
        candidate = f"{base}-{suffix:02d}"
        suffix += 1
    return candidate, now.isoformat(timespec="seconds")


def event_rows(work: dict[str, Any]) -> tuple[list[dict[str, Any]], list[str]]:
    rows, issues = [], []
    timezone = ZoneInfo(work["timezone"])
    for path in files_in(work["sessions_dir"]):
        fields, body = front_matter(path)
        if not fields:
            continue
        kind = fields.get("type", "").upper()
        if kind not in EVENT_TYPES:
            issues.append(f"ERROR: {path.relative_to(ROOT)}: invalid event type '{kind}'")
            continue
        stamp = fields.get("time", "")
        resolved = stamp
        if stamp == "PENDING":
            resolved = git_time(path, timezone) or "PENDING"
        if resolved != "PENDING":
            try:
                datetime.fromisoformat(resolved)
            except ValueError:
                issues.append(f"ERROR: {path.relative_to(ROOT)}: invalid ISO timestamp '{resolved}'")
                continue
        elif work["validate"]:
            issues.append(f"ERROR: {path.relative_to(ROOT)}: PENDING time has no Git commit timestamp")
        rows.append({
            "path": path, "type": kind, "time": resolved,
            "summary": fields.get("summary", "").strip(),
            "paths": fields.get("paths", ""),
            "related": fields.get("related", ""),
            "commit": fields.get("commit", "-"),
            "remote": fields.get("remote", "-"),
            "branch": fields.get("branch", "-"),
            "body": body,
        })
    rows.sort(key=lambda x: (x["time"], x["path"].as_posix()))
    used: Counter[str] = Counter()
    for row in rows:
        if row["time"] == "PENDING":
            row["id"] = f"PENDING-{row['type']}-{row['path'].stem}"
            continue
        dt = datetime.fromisoformat(row["time"])
        base = dt.strftime("%Y%m%d-%H%M%S") + "-" + row["type"]
        used[base] += 1
        row["id"] = base if used[base] == 1 else f"{base}-{used[base]:02d}"
    return rows, issues


def read_skeleton(path: Path) -> dict[str, Any]:
    fields: dict[str, str] = {}
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    for line in lines[:100]:
        match = META.search(line)
        if match:
            fields[match.group(1)] = match.group(2).strip()
    required = ("version", "kind", "target", "source_idea", "status", "priority",
                "spec_revision", "implemented_revision", "planned_in",
                "last_updated_in", "implemented_in", "blocker_ref", "resolution_of")
    missing = [x for x in required if not fields.get(x)]
    if missing:
        return {"file": path, "fields": fields, "lines": lines, "error": "missing metadata: " + ", ".join(missing)}
    try:
        spec, impl = int(fields["spec_revision"]), int(fields["implemented_revision"])
    except ValueError:
        return {"file": path, "fields": fields, "lines": lines, "error": "revision fields must be integers"}
    fields["status"] = fields["status"].upper()
    fields["kind"] = fields["kind"].upper()
    return {"file": path, "fields": fields, "lines": lines, "spec": spec, "impl": impl}


def all_skeletons(work: dict[str, Any]) -> list[dict[str, Any]]:
    items = []
    for path in sorted(p for p in work["skeleton_dir"].rglob("*") if p.is_file() and p.name != "README.md"):
        items.append(read_skeleton(path))
    return items


def run_rows(work: dict[str, Any]) -> tuple[list[dict[str, Any]], list[str]]:
    rows, issues = [], []
    for path in files_in(work["runs_dir"]):
        fields, body = front_matter(path)
        if not fields:
            continue
        required = ("id", "type", "time", "result")
        missing = [x for x in required if not fields.get(x)]
        if missing:
            issues.append(f"ERROR: {path.relative_to(ROOT)}: missing run fields: {', '.join(missing)}")
            continue
        fields["result"] = fields["result"].upper()
        fields["type"] = fields["type"].upper()
        rows.append({"path": path, "fields": fields, "body": body, **fields})
    return rows, issues


def extract_checks(lines: list[str]) -> list[dict[str, str]]:
    checks = []
    current = None
    for line in lines:
        heading = re.match(r"^###\s+(CHECK-[A-Z0-9-]+)", line)
        if heading:
            if current:
                checks.append(current)
            current = {"id": heading.group(1), "body": ""}
        elif current:
            current["body"] += line + "\n"
    if current:
        checks.append(current)
    for item in checks:
        body = item["body"]
        for key in ("Command", "Predicted output", "Pass condition", "Fail condition"):
            found = re.search(rf"^-\s*{re.escape(key)}:\s*(.+)$", body, re.M | re.I)
            item[key.lower()] = found.group(1).strip(" `") if found else ""
    return checks


def load_workspace(validate: bool = False) -> dict[str, Any]:
    cfg = parse_config(ROOT / ".stageset" / "config.yml")
    workspace_root = inside(ROOT, cfg.get("workspace.root", "."), "workspace.root")
    skeleton_dir = inside(workspace_root, cfg.get("workspace.skeletons_dir", "Skeletons"), "workspace.skeletons_dir")
    ideas_dir = inside(workspace_root, cfg.get("workspace.ideas_dir", "Ideas"), "workspace.ideas_dir")
    code_dir = inside(workspace_root, cfg.get("workspace.code_dir", "Code"), "workspace.code_dir")
    sessions_dir = inside(ROOT, cfg.get("tracking.sessions_dir", ".stageset/sessions"), "tracking.sessions_dir")
    runs_dir = inside(ROOT, cfg.get("runs.reports_dir", ".stageset/runs"), "runs.reports_dir")
    return {
        "cfg": cfg, "timezone": cfg.get("timezone", "Asia/Kolkata"),
        "workspace_root": workspace_root, "skeleton_dir": skeleton_dir,
        "ideas_dir": ideas_dir, "code_dir": code_dir,
        "sessions_dir": sessions_dir, "runs_dir": runs_dir,
        "facts_path": inside(ROOT, cfg.get("runs.facts_file", ".stageset/facts.md"), "runs.facts_file"),
        "digest_path": inside(ROOT, cfg.get("runs.digest_file", ".stageset/DIGEST.md"), "runs.digest_file"),
        "tracker_path": inside(ROOT, cfg.get("tracking.sessions_tracker", ".stageset/sessions-tracker.md"), "tracking.sessions_tracker"),
        "escalations_dir": inside(ROOT, cfg.get("runs.escalation_dir", ".stageset/escalations"), "runs.escalation_dir"),
        "max_attempts": int(cfg.get("runs.max_attempts_per_check", "3")),
        "validate": validate,
    }


def digest_content(events: list[dict[str, Any]], skeletons: list[dict[str, Any]], runs: list[dict[str, Any]], work: dict[str, Any]) -> str:
    ready = [s for s in skeletons if "error" not in s and s["fields"]["status"] in {"READY", "IN_PROGRESS"} and s["spec"] > s["impl"]]
    blocked = [s for s in skeletons if "error" not in s and s["fields"]["status"] == "BLOCKED"]
    failing = [r for r in runs if r["result"] == "FAIL"]
    facts = work["facts_path"].read_text(encoding="utf-8").splitlines() if work["facts_path"].exists() else []
    fact_rows = [line for line in facts if line.startswith("| FACT-") and "SUPERSEDED" not in line]
    out = [ "# StageSet digest", "", GENERATED, "", "This file is generated. Do not edit it by hand.", "",
            "## Ready skeletons", "" ]
    out.extend([f"- [{s['fields']['priority']}] `{s['file'].relative_to(ROOT)}` (revision {s['spec']}, implemented {s['impl']})." for s in ready] or ["- None."])
    out += ["", "## Open blockers", ""]
    out.extend([f"- `{s['file'].relative_to(ROOT)}` — `{s['fields'].get('blocker_ref', '-')}`." for s in blocked] or ["- None."])
    out += ["", "## Failing checks", ""]
    out.extend([f"- `{r['id']}` — `{r['skeleton']}`, `{r['check_id']}`, attempt {r['attempt']}." for r in failing[-20:]] or ["- None."])
    out += ["", "## Last 5 sessions", ""]
    out.extend([f"- {e['id']} · {e['type']} · {e['summary'] or e['path'].stem}." for e in events[-5:][::-1]] or ["- None."])
    out += ["", "## Verified environment facts", ""]
    out.extend(fact_rows[-20:] or ["- None."])
    out += ["", "## Read next", "", "1. Read the rules for your role.", "2. Read the listed skeleton and idea files.", "3. Read linked run reports before you handle a blocker.", "4. Check `.stageset/facts.md` before you make an environment assumption.", ""]
    return "\n".join(out)


def tracker_content(events: list[dict[str, Any]]) -> str:
    out = ["# StageSet sessions tracker", "", GENERATED, "",
           "This file is generated from `.stageset/sessions/`. Do not edit it by hand.", "",
           "| Event ID | Type | Timestamp | Summary | Event file | Related | Commit / Push |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for e in events:
        vals = [e["id"], e["type"], e["time"], e["summary"], e["path"].relative_to(ROOT).as_posix(),
                e["related"] or "-", e["commit"]]
        out.append("| " + " | ".join(str(v).replace("|", "\\|") for v in vals) + " |")
    counts = Counter(e["type"] for e in events)
    out += ["", "## Totals", ""]
    out += [f"- {kind}: {counts[kind]}." for kind in sorted(EVENT_TYPES)]
    out.append("")
    return "\n".join(out)


def create_escalation(work: dict[str, Any], check_id: str, skeletons: list[dict[str, Any]], runs: list[dict[str, Any]]) -> Path:
    matching_skeletons = [s for s in skeletons if "error" not in s and any(c["id"] == check_id for c in extract_checks(s["lines"]))]
    if len(matching_skeletons) != 1:
        raise ValueError(f"Expected one skeleton for {check_id}; found {len(matching_skeletons)}")
    skel = matching_skeletons[0]
    sf = skel["fields"]
    current = [r for r in runs if r.get("check_id") == check_id and r.get("skeleton") == skel["file"].relative_to(ROOT).as_posix() and str(r.get("spec_revision")) == str(skel["spec"])]
    current.sort(key=lambda r: int(r.get("attempt", "0")))
    failed = [r for r in current if r["result"] == "FAIL"]
    if len(failed) < 3:
        raise ValueError(f"{check_id} has {len(failed)} failed attempts on revision {skel['spec']}; three are required")
    latest = failed[-1]
    expected = f"{work['runs_dir'].relative_to(ROOT).as_posix()}/{latest['id']}.md"
    if sf["status"] != "BLOCKED" or sf.get("blocker_ref") != expected:
        raise ValueError(f"Set skeleton status to BLOCKED and blocker_ref to {expected} first")
    work["escalations_dir"].mkdir(parents=True, exist_ok=True)
    escalation_id, created_at = timestamp_id("ESCALATION", work["escalations_dir"], work["timezone"])
    out = ["---", f"id: {escalation_id}", f"time: {created_at}", "---", "",
           f"# Escalation: {check_id}", "", GENERATED, "",
           f"- Skeleton: `{skel['file'].relative_to(ROOT)}`",
           f"- Check: `{check_id}`",
           f"- Failed attempts: {len(failed)}",
           f"- Latest run: `{latest['id']}`", "",
           "## Failure summary", "", f"The check failed {len(failed)} times on revision {skel['spec']}. Stop implementation. Do not redesign the feature.", "",
           "## Attempts", ""]
    for r in failed[-3:]:
        out += [f"### {r['id']} — attempt {r.get('attempt')}", "", f"- Command: `{r.get('command', '')}`", "", "#### Observed output", "", heading_block(r["body"], "Observed output (trimmed)"), "", "#### Tried", "", heading_block(r["body"], "Tried"), "", "#### Attempt diff", "", heading_block(r["body"], "Attempt diff"), "", "#### Smallest repro", "", heading_block(r["body"], "Smallest repro"), ""]
    run_refs = ", ".join("`" + r["path"].relative_to(ROOT).as_posix() + "`" for r in failed[-3:])
    out += ["## Planner action", "", f"Read the skeleton and these run reports: {run_refs}.", "",
            "Update the skeleton to resolve the verified blocker. Increase `spec_revision` by one. Keep `implemented_revision` unchanged. Set `status: READY`. Set `blocker_ref: -`. Set `resolution_of` to the latest run ID.", "",
            "The coder must implement only the revised skeleton. The coder must not redesign the feature.", ""]
    dest = work["escalations_dir"] / f"{escalation_id}.md"
    # Exclusive creation prevents two agents from overwriting the same escalation.
    while True:
        try:
            with dest.open("x", encoding="utf-8") as handle:
                handle.write("\n".join(out))
            break
        except FileExistsError:
            escalation_id, created_at = timestamp_id("ESCALATION", work["escalations_dir"], work["timezone"])
            out[1] = f"id: {escalation_id}"
            out[2] = f"time: {created_at}"
            dest = work["escalations_dir"] / f"{escalation_id}.md"
    return dest


def heading_block(body: str, heading: str) -> str:
    pattern = rf"##\s+{re.escape(heading)}\s*\n(.*?)(?=\n##\s+|\Z)"
    match = re.search(pattern, body, re.S | re.I)
    return match.group(1).strip() if match else "_Not recorded._"


def validate(work: dict[str, Any], skeletons: list[dict[str, Any]], runs: list[dict[str, Any]], events: list[dict[str, Any]], issues: list[str]) -> list[str]:
    errors = list(issues)
    # Validate idea documents. The index and README are navigation files.
    for idea_path in files_in(work["ideas_dir"]):
        if idea_path.name in {"README.md", "_index.md"}:
            continue
        idea_fields, _ = front_matter(idea_path)
        for key in ("id", "title", "status", "priority", "created_in", "updated_in"):
            if not idea_fields.get(key):
                errors.append(f"ERROR: {idea_path.relative_to(ROOT)}: missing idea field {key}")
        if idea_fields.get("status", "").upper() not in IDEA_STATES:
            errors.append(f"ERROR: {idea_path.relative_to(ROOT)}: invalid idea status {idea_fields.get('status', '')}")
        for key in ("created_in", "updated_in"):
            event_ref = idea_fields.get(key, "")
            if event_ref and event_ref != "-" and not (ROOT / event_ref).is_file():
                errors.append(f"ERROR: {idea_path.relative_to(ROOT)}: {key} does not point to an event file")
    valid_runs = {r["path"].relative_to(ROOT).as_posix(): r for r in runs}
    all_run_ids = {r["id"] for r in runs}
    for reservation in work["runs_dir"].glob(".*.reserve") if work["runs_dir"].is_dir() else []:
        errors.append(f"ERROR: {reservation.relative_to(ROOT)}: run ID reservation remains; create the report and remove this reservation file")
    check_ids: set[str] = set()
    for s in skeletons:
        if "error" in s:
            errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: {s['error']}")
            continue
        f = s["fields"]
        if f["status"] not in SKELETON_STATES:
            errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: invalid status {f['status']}")
        if f["kind"] not in {"IMPLEMENTATION", "PROBE"}:
            errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: invalid kind {f['kind']}")
        if f["kind"] == "IMPLEMENTATION":
            target = Path(f["target"])
            expected = work["skeleton_dir"] / (str(target) + (".skeleton.md" if s["file"].name.endswith(".skeleton.md") else ""))
            if s["file"].resolve() != expected.resolve():
                errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: skeleton path does not mirror target {target}")
            if not f["target"] or target.is_absolute() or ".." in target.parts:
                errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: unsafe target path")
        elif f["target"] != "-":
            errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: probe target must be '-'")
        if s["spec"] < 1 or s["impl"] < 0 or s["impl"] > s["spec"]:
            errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: invalid revision values")
        if f["status"] == "BLOCKED":
            if f["blocker_ref"] not in valid_runs:
                errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: blocker_ref does not point to a run report")
        elif f["blocker_ref"] != "-":
            errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: non-blocked skeleton must set blocker_ref to '-'")
        if f["resolution_of"] != "-" and f["resolution_of"] not in all_run_ids:
            errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: resolution_of does not point to a run ID")
        if f["kind"] == "IMPLEMENTATION":
            if "## Checks" not in "\n".join(s["lines"]):
                errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: missing Checks section")
            for check in extract_checks(s["lines"]):
                if check["id"] in check_ids:
                    errors.append(f"ERROR: duplicate check ID {check['id']}")
                check_ids.add(check["id"])
                for field in ("command", "predicted output", "pass condition", "fail condition"):
                    if not check.get(field):
                        errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: {check['id']} missing {field}")
        for line in s["lines"]:
            if "ASSUMPTION:" in line and not re.search(r"ASSUMPTION:\s*A-\d{2}", line):
                errors.append(f"ERROR: {s['file'].relative_to(ROOT)}: assumption tag needs ID A-01")
    for r in runs:
        if not re.fullmatch(r"\d{8}-\d{6}-RUN(?:-\d{2})?", r["id"]):
            errors.append(f"ERROR: {r['path'].relative_to(ROOT)}: run ID must use YYYYMMDD-HHMMSS-RUN format")
        if r["path"].stem != r["id"]:
            errors.append(f"ERROR: {r['path'].relative_to(ROOT)}: run filename must match its ID")
        if r["result"] not in RUN_RESULTS:
            errors.append(f"ERROR: {r['path'].relative_to(ROOT)}: invalid result {r['result']}")
        if r["type"] not in {"CHECK", "PROBE", "IMPLEMENTATION"}:
            errors.append(f"ERROR: {r['path'].relative_to(ROOT)}: invalid run type {r['type']}")
        for heading in ("Goal", "Commands", "Observed output (trimmed)", "Result", "Facts", "Guesses",
                        "Assumptions checked", "Tried", "Open question for planner"):
            if not re.search(rf"^##\s+{re.escape(heading)}\s*$", r["body"], re.M | re.I):
                errors.append(f"ERROR: {r['path'].relative_to(ROOT)}: missing section {heading}")
        if not r.get("command"):
            errors.append(f"ERROR: {r['path'].relative_to(ROOT)}: missing command in front matter")
    for event in events:
        if event["time"] == "PENDING":
            errors.append(f"ERROR: {event['path'].relative_to(ROOT)}: unresolved PENDING time")
    expected_tracker = tracker_content(events)
    expected_digest = digest_content(events, skeletons, runs, work)
    if not work["tracker_path"].is_file() or work["tracker_path"].read_text(encoding="utf-8") != expected_tracker:
        errors.append("ERROR: generated session tracker is missing or stale; run --sync")
    if not work["digest_path"].is_file() or work["digest_path"].read_text(encoding="utf-8") != expected_digest:
        errors.append("ERROR: generated digest is missing or stale; run --sync")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="Print machine-readable status.")
    parser.add_argument("--sync", action="store_true", help="Regenerate the tracker and digest.")
    parser.add_argument("--digest", action="store_true", help="Regenerate only the digest.")
    parser.add_argument("--validate", action="store_true", help="Validate StageSet files.")
    parser.add_argument("--new-run-id", action="store_true", help="Print a timestamp-based run ID for a new report.")
    parser.add_argument("--escalate", metavar="CHECK-ID", help="Build a timestamp-based escalation after three failed attempts.")
    args = parser.parse_args()
    try:
        work = load_workspace(validate=args.validate)
        skeletons = all_skeletons(work)
        runs, run_issues = run_rows(work)
        events, event_issues = event_rows(work)
        if args.new_run_id:
            work["runs_dir"].mkdir(parents=True, exist_ok=True)
            while True:
                run_id, run_time = timestamp_id("RUN", work["runs_dir"], work["timezone"])
                reservation = work["runs_dir"] / f".{run_id}.reserve"
                try:
                    with reservation.open("x", encoding="utf-8") as handle:
                        handle.write(run_time)
                    print(run_id)
                    return 0
                except FileExistsError:
                    # Another agent reserved this ID after the availability check.
                    continue
        if args.escalate:
            path = create_escalation(work, args.escalate, skeletons, runs)
            print(f"Created {path.relative_to(ROOT)}")
            return 0
        if args.sync:
            work["tracker_path"].parent.mkdir(parents=True, exist_ok=True)
            work["digest_path"].parent.mkdir(parents=True, exist_ok=True)
            work["tracker_path"].write_text(tracker_content(events), encoding="utf-8")
            work["digest_path"].write_text(digest_content(events, skeletons, runs, work), encoding="utf-8")
            print("Updated .stageset/sessions-tracker.md and .stageset/DIGEST.md")
            return 0
        if args.digest:
            work["digest_path"].parent.mkdir(parents=True, exist_ok=True)
            work["digest_path"].write_text(digest_content(events, skeletons, runs, work), encoding="utf-8")
            print("Updated .stageset/DIGEST.md")
            return 0
        if args.validate:
            errors = validate(work, skeletons, runs, events, event_issues + run_issues)
            if errors:
                print("\n".join(errors))
                return 1
            print("StageSet validation passed.")
            return 0
        pending = [s for s in skeletons if "error" not in s and s["fields"]["status"] in {"READY", "IN_PROGRESS"} and s["spec"] > s["impl"]]
        blocked = [s for s in skeletons if "error" not in s and s["fields"]["status"] == "BLOCKED"]
        failed = [r for r in runs if r["result"] == "FAIL"]
        if args.json:
            print(json.dumps({
                "ready_skeletons": [s["file"].relative_to(ROOT).as_posix() for s in pending],
                "blocked_skeletons": [s["file"].relative_to(ROOT).as_posix() for s in blocked],
                "failed_runs": [r["path"].relative_to(ROOT).as_posix() for r in failed],
                "events": len(events),
                "latest_event": events[-1]["id"] if events else None,
            }, indent=2))
        else:
            print("StageSet status")
            print(f"Ready skeletons: {len(pending)}")
            for s in pending:
                print(f"- {s['file'].relative_to(ROOT)} (revision {s['spec']})")
            print(f"Open blockers: {len(blocked)}")
            for s in blocked:
                print(f"- {s['file'].relative_to(ROOT)} -> {s['fields']['blocker_ref']}")
            print(f"Failing checks: {len(failed)}")
            print(f"Events: {len(events)}")
        return 0
    except (OSError, ValueError, KeyError) as exc:
        print(f"StageSet error: {exc}", file=sys.stderr)
        return 2


